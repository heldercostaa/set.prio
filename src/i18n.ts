export function messages(language: Language) {
  return language === 'pt-BR' ? pt : en;
}
const priorityLabels = {
  en: {
    P0: 'Can’t miss',
    P1: 'Must see',
    P2: 'Could be good',
    P3: 'Curious',
    P4: "I'd rather eat glass",
  },
  'pt-BR': {
    P0: 'Imperdível',
    P1: 'Faço questão',
    P2: 'Pode ser',
    P3: 'Curioso',
    P4: 'Prefiro cair de moto',
  },
};
export function priorityHasCode(priority: Priority) {
  return priority !== 'P3' && priority !== 'P4';
}
export function priorityLabel(priority: Priority, language: Language) {
  return priorityLabels[language][priority];
}
export function dayName(day: Day | null, language: Language) {
  if (!day) return messages(language).dayTba;
  return (
    language === 'pt-BR' ? ['Sexta-feira', 'Sábado', 'Domingo'] : ['Friday', 'Saturday', 'Sunday']
  )[DAYS.indexOf(day)];
}
export function shortDate(day: string, language: Language) {
  return new Intl.DateTimeFormat(language, {
    month: 'short',
    day: 'numeric',
    timeZone: 'UTC',
  }).format(new Date(`${day}T12:00:00Z`));
}
export function longDate(day: string, language: Language) {
  return new Intl.DateTimeFormat(language, {
    month: 'long',
    day: 'numeric',
    year: 'numeric',
    timeZone: 'UTC',
  }).format(new Date(`${day}T12:00:00Z`));
}
